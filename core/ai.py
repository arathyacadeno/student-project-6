"""Google Gemini integration (REST) with an offline fallback planner."""
import json
import urllib.request

from django.conf import settings


def gemini(prompt):
    """Call Gemini and return text, or None when no key is set / the call fails."""
    if not settings.GEMINI_API_KEY:
        return None
    models_to_try = [settings.GEMINI_MODEL, "gemini-flash-lite-latest", "gemini-3.8-flash", "gemini-flash-latest"]
    seen = set()
    models = [m for m in models_to_try if m and not (m in seen or seen.add(m))]

    body = json.dumps({"contents": [{"parts": [{"text": prompt}]}]}).encode()
    for model in models:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
        req = urllib.request.Request(url, data=body, headers={
            "Content-Type": "application/json", "x-goog-api-key": settings.GEMINI_API_KEY})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.load(resp)
            return data["candidates"][0]["content"]["parts"][0]["text"]
        except Exception:
            continue
    return None


def generate_itinerary(dest, days, travellers, budget, interests, start_date=None):
    """Returns (markdown_text, source) where source is 'gemini' or 'offline'."""
    hotels = ", ".join(f"{h.name} (₹{h.price_per_night}/night)" for h in dest.hotels.all()[:4]) or "n/a"
    acts = ", ".join(f"{a.name} (₹{a.cost})" for a in dest.activities.all()[:6]) or "n/a"
    prompt = (
        f"You are TravelMate AI, a friendly travel planner. Create a {days}-day itinerary for "
        f"{dest.name}, {dest.district}, {dest.state}, India for {travellers} traveller(s) with a total budget of "
        f"₹{budget}. Start date: {start_date or 'flexible'}. Interests: {interests or 'general sightseeing'}.\n"
        f"Known attractions: {', '.join(dest.attraction_list)}. Hotels: {hotels}. Activities: {acts}.\n"
        "Format in Markdown: use '## Day N - title' headings, bullet points with morning / afternoon / evening, "
        "then '## Estimated budget' with a breakdown in INR (stay, food, transport, activities) and '## Travel tips'. "
        "Keep it concise and practical."
    )
    text = gemini(prompt)
    if text:
        return text, "gemini"
    return offline_itinerary(dest, days, travellers, budget, interests), "offline"


def offline_itinerary(dest, days, travellers, budget, interests):
    attractions = dest.attraction_list or [dest.name]
    acts = list(dest.activities.all())
    hotels = sorted(dest.hotels.all(), key=lambda h: h.price_per_night)
    per_night_budget = budget * 0.4 / max(days, 1) if budget else None
    hotel = next((h for h in hotels if per_night_budget and h.price_per_night * ((travellers + 1) // 2) <= per_night_budget),
                 hotels[0] if hotels else None)
    lines = [f"## Trip overview", f"- {days} days in **{dest.name}**, {dest.district} for {travellers} traveller(s)",
             f"- Focus: {interests or 'sightseeing and relaxation'}"]
    if hotel:
        lines.append(f"- Suggested stay: **{hotel.name}** (₹{hotel.price_per_night}/night)")
    activity_cost = 0
    for d in range(days):
        a1 = attractions[(2 * d) % len(attractions)]
        a2 = attractions[(2 * d + 1) % len(attractions)]
        lines += ["", f"## Day {d + 1} - {a1}",
                  f"- Morning: visit {a1}", f"- Afternoon: explore {a2} and have a local lunch"]
        if acts:
            act = acts[d % len(acts)]
            activity_cost += act.cost * travellers
            lines.append(f"- Evening: {act.name} (about ₹{act.cost} per person)")
        else:
            lines.append("- Evening: relax and try local Kerala snacks")
    rooms = (travellers + 1) // 2
    stay = (hotel.price_per_night if hotel else 1500) * rooms * max(days - 1, 1)
    food = 700 * travellers * days
    transport = 900 * days
    total = stay + food + transport + activity_cost
    lines += ["", "## Estimated budget",
              f"- Stay: ₹{stay}", f"- Food: ₹{food}", f"- Local transport: ₹{transport}",
              f"- Activities: ₹{activity_cost}", f"- **Total: ₹{total}**"]
    if budget:
        lines.append("- Within your budget ✔" if total <= budget else f"- About ₹{total - budget} over budget - try the Cost Optimizer tool.")
    lines += ["", "## Travel tips", "- Carry a photo ID and some cash for small shops.",
              "- Start early to avoid crowds at popular spots.",
              "*Generated by the built-in offline planner. Add a GEMINI_API_KEY to get Gemini-written plans.*"]
    return "\n".join(lines)


def answer_question(question, dest=None):
    ctx = f" The traveller is interested in {dest.name}, {dest.district}." if dest else ""
    text = gemini("You are TravelMate AI, a concise travel assistant for India. Answer helpfully in under 150 words." + ctx +
                  f"\nQuestion: {question}")
    if text:
        return text
    return ("The AI assistant needs a Gemini API key to answer free-form questions. "
            "Set the GEMINI_API_KEY environment variable and restart the server.")
